#!/usr/bin/env python3
"""src/Fill the Word.dc.html  ->  dist/pwa/ (index.html, manifest.webmanifest, sw.js, icons/)

This is the installable target: a real static-file bundle meant to be hosted
(GitHub Pages, Netlify, Vercel, any static host over HTTPS) so "Add to Home
Screen" / desktop install actually works. It is NOT the same file as
dist/artifact.html or the standalone bundle — a Claude Artifact runs inside a
sandboxed iframe and can't register a service worker or trigger an install
prompt no matter what markup it contains, so this target exists separately
for whoever deploys it to real hosting.

index.html itself still inlines React/ReactDOM/the runtime/fonts exactly like
the other two builds (same _shared helpers), so it makes zero network calls
once cached — the manifest, icons and service worker are the only extra
files, and the service worker's whole job is caching that one HTML file for
offline use.
"""
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _shared import (  # noqa: E402
    DIST, SRC, SUPPORT, assets, check_support_matches_bundle, escape_script,
    font_face_css, react_pair, read_shell, UUID_RE,
)
sys.path.insert(0, str(Path(__file__).resolve().parent / "pwa-assets"))
from make_icons import generate as generate_icons  # noqa: E402

ICON_SRC = Path(__file__).parent / "pwa-assets"
PWA_DIR = DIST / "pwa"
APP_NAME = "Fill the Word"
DESCRIPTION = "Fill in the missing words of a Bible verse from memory — a daily challenge verse, or your own passage taken up a difficulty ladder."
THEME_LIGHT = "#faf7f0"
THEME_DARK = "#16140f"

MANIFEST = {
    "name": APP_NAME,
    "short_name": APP_NAME,
    "description": DESCRIPTION,
    "id": "/",
    "start_url": "./index.html",
    "scope": "./",
    "display": "standalone",
    "display_override": ["window-controls-overlay", "standalone"],
    "orientation": "portrait-primary",
    "background_color": THEME_LIGHT,
    "theme_color": THEME_LIGHT,
    "icons": [
        {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-192-maskable.png", "sizes": "192x192", "type": "image/png", "purpose": "maskable"},
        {"src": "icons/icon-512-maskable.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}

# Cache-name is versioned by hand — bump it whenever index.html changes so a
# returning visitor's old service worker replaces its cached copy instead of
# serving stale HTML forever. (The build stamps the real value in below.)
#
# The document itself (the one HTML file the whole app is) is fetched
# network-first, falling back to the cache only when offline. GitHub Pages
# (and most static hosts) sets its own Cache-Control on sw.js that we can't
# override, so relying on the browser's own "is sw.js byte-different?"
# update check to notice a new build is slow and inconsistent — a returning
# visitor could easily launch the app several times before it happens to
# recheck. Network-first for the document sidesteps that whole race: whenever
# there's connectivity, the next launch always gets the latest build,
# immediately, no waiting on service-worker update timing at all. Everything
# else (manifest, icons — static, rarely changes) stays cache-first.
SW_TEMPLATE = """// Generated by build/build_pwa.py — do not edit by hand.
const CACHE = "fill-the-word-%(version)s";
const APP_SHELL = ["./", "./index.html", "./manifest.webmanifest"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(APP_SHELL)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((n) => n !== CACHE).map((n) => caches.delete(n)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const isDoc = event.request.mode === "navigate" || event.request.url.endsWith("/index.html");
  if (isDoc) {
    // cache: "no-store" bypasses the browser's own HTTP cache for this fetch
    // (separate from, and in addition to, the CacheStorage read/write below)
    // — without it, a host that doesn't send strong no-cache headers (or a
    // dev server that sends none at all) can let the browser's heuristic
    // freshness rules quietly serve this exact request from HTTP cache,
    // silently defeating the whole point of fetching fresh on every launch.
    event.respondWith(
      fetch(event.request, { cache: "no-store" }).then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(event.request, copy));
        }
        return res;
      }).catch(() => caches.match(event.request).then((hit) => hit || caches.match("./index.html")))
    );
    return;
  }
  event.respondWith(
    caches.match(event.request).then((hit) => {
      if (hit) return hit;
      return fetch(event.request).then((res) => {
        if (res.ok && event.request.url.startsWith(self.location.origin)) {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(event.request, copy));
        }
        return res;
      }).catch(() => caches.match("./index.html"));
    })
  );
});
"""

# A plain (non-React) script: registers the service worker, and — separately
# — tells a returning visitor when they've just landed on a newer build than
# the one they last saw, via a small toast. Compares a version stamp (the
# same content hash used to bust the SW cache) against one stashed in
# localStorage under its own key, deliberately not the app's own save key,
# so this never touches real save data. Silent on first-ever visit (nothing
# to compare against yet) and on any later visit that's still the same
# build — it only speaks up when the version actually just changed.
SW_REGISTER = """<script>
if ("serviceWorker" in navigator) {
  window.addEventListener("load", () => {
    navigator.serviceWorker.register("./sw.js").then((reg) => {
      // Ask explicitly, on top of whatever automatic check the browser
      // does on its own timing — an already-installed app can otherwise
      // sit on an old worker for a while before that fires on its own.
      // Re-checking on every foreground (not just cold launch) covers an
      // installed app that resumes an existing background process rather
      // than doing a fresh navigation when reopened.
      reg.update().catch(() => {});
      document.addEventListener("visibilitychange", () => {
        if (document.visibilityState === "visible") reg.update().catch(() => {});
      });
    }).catch(() => {});
  });
}
(function() {
  var VERSION = "__SW_VERSION__";
  var KEY = "filltheword.seenVersion";
  try {
    var seen = localStorage.getItem(KEY);
    if (seen && seen !== VERSION) {
      window.addEventListener("load", function() {
        var el = document.createElement("div");
        el.textContent = "Updated to the latest version";
        el.setAttribute("role", "status");
        el.style.cssText = "position:fixed;left:50%;bottom:28px;transform:translateX(-50%);background:#2a2318;color:#fff;padding:12px 20px;border-radius:99px;font:600 13.5px Figtree,ui-sans-serif,system-ui,sans-serif;box-shadow:0 10px 28px rgba(0,0,0,.35);z-index:99999;opacity:0;transition:opacity .3s ease;pointer-events:none";
        document.body.appendChild(el);
        requestAnimationFrame(function() { el.style.opacity = "1"; });
        setTimeout(function() {
          el.style.opacity = "0";
          setTimeout(function() { el.remove(); }, 300);
        }, 3500);
      });
    }
    localStorage.setItem(KEY, VERSION);
  } catch (e) { /* private mode, blocked storage — just skip the toast */ }
})();
</script>"""


def build_index():
    _, manifest, template = read_shell()
    assets_map = assets(manifest)
    check_support_matches_bundle(assets_map)

    react, react_dom = react_pair(assets_map)
    runtime = SUPPORT.read_text(encoding="utf-8")
    src = SRC.read_text(encoding="utf-8")

    inline = "\n".join(
        "<script>%s</script>" % escape_script(js) for js in (react, react_dom, runtime)
    )
    tag = '<script src="./support.js"></script>'
    assert tag in src, "runtime script tag not found in the source"
    src = src.replace(tag, inline, 1)

    link = re.search(r'<link href="https://fonts\.googleapis\.com/css2[^"]*" rel="stylesheet">', src)
    assert link, "Google Fonts link not found in the source"
    src = src.replace(link.group(0), font_face_css(template, assets_map), 1)

    head = src[src.index("<head>") + len("<head>"):src.index("</head>")]
    body = src[src.index("<body>") + len("<body>"):src.rindex("</body>")]

    pwa_head_extras = (
        '<link rel="manifest" href="./manifest.webmanifest">\n'
        '<link rel="icon" href="./icons/favicon.ico">\n'
        '<link rel="apple-touch-icon" href="./icons/apple-touch-icon.png">\n'
        '<meta name="mobile-web-app-capable" content="yes">\n'
        '<meta name="apple-mobile-web-app-capable" content="yes">\n'
        '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">\n'
        '<meta name="apple-mobile-web-app-title" content="%s">' % APP_NAME
    )

    doc = (
        "<!doctype html>\n<html>\n<head>\n"
        '<meta charset="utf-8">\n'
        "<title>%s</title>\n" % APP_NAME
        + pwa_head_extras + "\n"
        + head.strip() + "\n"
        "</head>\n<body>\n"
        "<script>window.__resources = window.__resources || {};</script>\n"
        + body.strip() + "\n"
        + SW_REGISTER + "\n"
        "</body>\n</html>\n"
    )

    leftover = re.findall(UUID_RE, doc)
    assert not leftover, "unresolved bundle uuids: %s" % set(leftover)
    return doc


def main():
    if PWA_DIR.exists():
        shutil.rmtree(PWA_DIR)
    (PWA_DIR / "icons").mkdir(parents=True)
    generate_icons(ICON_SRC)

    index = build_index()

    # Version the cache (and the "you're on a new build" toast) by the index
    # content, so a real change always busts both — hashed before the
    # placeholder is resolved, since the placeholder text itself is constant
    # and doesn't need to feed back into its own hash.
    import hashlib
    version = hashlib.sha1(index.encode("utf-8")).hexdigest()[:10]
    index = index.replace("__SW_VERSION__", version)
    (PWA_DIR / "index.html").write_text(index, encoding="utf-8")
    (PWA_DIR / "sw.js").write_text(SW_TEMPLATE % {"version": version}, encoding="utf-8")

    (PWA_DIR / "manifest.webmanifest").write_text(
        json.dumps(MANIFEST, indent=2) + "\n", encoding="utf-8"
    )

    for name in ("icon-192.png", "icon-512.png", "icon-192-maskable.png",
                 "icon-512-maskable.png", "apple-touch-icon.png", "favicon.ico"):
        shutil.copyfile(ICON_SRC / name, PWA_DIR / "icons" / name)

    total = sum(f.stat().st_size for f in PWA_DIR.rglob("*") if f.is_file())
    print("dist/pwa/index.html          %7d bytes" % len(index))
    print("dist/pwa/manifest.webmanifest")
    print("dist/pwa/sw.js                 (cache %s)" % version)
    print("dist/pwa/icons/  (6 files)")
    print("dist/pwa total: %d bytes" % total)


if __name__ == "__main__":
    main()
